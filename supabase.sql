-- 5. 匿名访客原子预定
create or replace function public.reserve_product(
  p_product_id uuid,
  p_buyer_name text,
  p_contact text,
  p_note text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_status text;
  v_quantity integer;
  v_sold_quantity integer;
  v_reservation_id uuid;
  v_connection_code text;
  v_management_wechat text;
begin
  if nullif(btrim(p_buyer_name),'') is null then raise exception '请填写姓名'; end if;
  if char_length(btrim(p_buyer_name)) > 40 then raise exception '姓名过长'; end if;
  if nullif(btrim(p_contact),'') is null then raise exception '请填写联系方式'; end if;
  if char_length(btrim(p_contact)) > 120 then raise exception '联系方式过长'; end if;
  if char_length(coalesce(p_note,'')) > 1000 then raise exception '备注过长'; end if;

  select status,quantity,sold_quantity,connection_code into v_status,v_quantity,v_sold_quantity,v_connection_code from public.products where id = p_product_id for update;
  if not found then raise exception '商品不存在'; end if;
  if v_status <> 'available' or v_sold_quantity >= v_quantity then raise exception '该商品已售罄或不可购买'; end if;

  insert into public.reservations(product_id,buyer_name,contact,note)
  values (p_product_id,btrim(p_buyer_name),btrim(p_contact),coalesce(btrim(p_note),''))
  returning id into v_reservation_id;

  select admin_wechat into v_management_wechat from public.site_settings where id=true;
  return jsonb_build_object('reservation_id',v_reservation_id,'connection_code',v_connection_code,'seller_wechat',coalesce(v_management_wechat,''));
end;
$$;

revoke all on function public.reserve_product(uuid,text,text,text) from public;
grant execute on function public.reserve_product(uuid,text,text,text) to anon, authenticated;

-- 6. 管理员确认或取消预定，并同步商品状态
create or replace function public.admin_set_reservation_status(p_reservation_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_product_id uuid;
  v_old_status text;
  v_quantity integer;
  v_sold_quantity integer;
  v_product_status text;
begin
  if not public.is_admin() then raise exception '无权限'; end if;
  if p_status not in ('confirmed','cancelled') then raise exception '无效状态'; end if;

  select product_id,status into v_product_id,v_old_status from public.reservations
  where id = p_reservation_id for update;
  if not found then raise exception '预定不存在'; end if;

  select quantity,sold_quantity,status into v_quantity,v_sold_quantity,v_product_status
  from public.products where id = v_product_id for update;
  if not found then raise exception '商品不存在'; end if;

  if v_old_status = p_status then return; end if;
  if p_status = 'confirmed' and v_sold_quantity >= v_quantity then
    raise exception '库存不足，无法确认成交';
  end if;

  update public.reservations set status = p_status where id = p_reservation_id;
  if p_status = 'confirmed' then
    update public.products set
      sold_quantity = sold_quantity + 1,
      status = case when sold_quantity + 1 >= quantity then 'sold' else 'available' end
    where id = v_product_id and status <> 'removed';
  else
    if v_old_status = 'confirmed' then
      update public.products set
        sold_quantity = greatest(sold_quantity - 1,0),
        status = case when status = 'removed' then 'removed' else 'available' end
      where id = v_product_id;
    end if;
  end if;
end;
$$;

revoke all on function public.admin_set_reservation_status(uuid,text) from public;
grant execute on function public.admin_set_reservation_status(uuid,text) to authenticated;

