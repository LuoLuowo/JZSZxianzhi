-- 已登录管理员可把 Authentication 中已存在的邮箱账号提升为管理员。
create or replace function public.admin_grant_admin(p_email text)
returns jsonb
language plpgsql
security definer
set search_path = public,auth,pg_temp
as $$
declare v_user_id uuid; v_nickname text;
begin
  if not public.is_admin() then raise exception '无权限'; end if;
  select id into v_user_id from auth.users where lower(email)=lower(btrim(p_email));
  if v_user_id is null then raise exception '该邮箱尚未在 Authentication Users 中创建账号'; end if;
  insert into public.profiles(id,nickname,is_admin)
  select id,split_part(coalesce(email,'管理员'),'@',1),true from auth.users where id=v_user_id
  on conflict(id) do update set is_admin=true;
  select nickname into v_nickname from public.profiles where id=v_user_id;
  return jsonb_build_object('id',v_user_id,'email',lower(btrim(p_email)),'nickname',v_nickname);
end;
$$;
revoke all on function public.admin_grant_admin(text) from public;
grant execute on function public.admin_grant_admin(text) to authenticated;

create or replace function public.admin_list_admins()
returns table(id uuid,email text,nickname text,created_at timestamptz)
language plpgsql
security definer
set search_path = public,auth,pg_temp
as $$
begin
  if not public.is_admin() then raise exception '无权限'; end if;
  return query select p.id,u.email::text,p.nickname,p.created_at
  from public.profiles p join auth.users u on u.id=p.id
  where p.is_admin=true order by p.created_at;
end;
$$;
revoke all on function public.admin_list_admins() from public;
grant execute on function public.admin_list_admins() to authenticated;

create or replace function public.admin_resource_usage()
returns jsonb
language plpgsql
security definer
set search_path = public,storage,pg_temp
as $$
declare
  v_storage_count bigint := 0;
  v_storage_bytes bigint := 0;
  v_database_bytes bigint := 0;
  v_product_images bigint := 0;
  v_external_images bigint := 0;
begin
  if not public.is_admin() then raise exception '无权限'; end if;
  select count(*),coalesce(sum(case when coalesce(metadata->>'size','') ~ '^[0-9]+$' then (metadata->>'size')::bigint else 0 end),0)
  into v_storage_count,v_storage_bytes from storage.objects where bucket_id='product-images';
  select count(*) filter(where image_url is not null),count(*) filter(where image_url is not null and image_url not like '%/storage/v1/object/public/product-images/%')
  into v_product_images,v_external_images from public.products;
  v_database_bytes := pg_total_relation_size('public.profiles'::regclass)+pg_total_relation_size('public.categories'::regclass)+pg_total_relation_size('public.hot_searches'::regclass)+pg_total_relation_size('public.products'::regclass)+pg_total_relation_size('public.reservations'::regclass)+pg_total_relation_size('public.product_code_registry'::regclass)+pg_total_relation_size('public.site_settings'::regclass);
  return jsonb_build_object('storage_image_count',v_storage_count,'storage_bytes',v_storage_bytes,'database_bytes',v_database_bytes,'total_bytes',v_storage_bytes+v_database_bytes,'product_image_count',v_product_images,'external_image_count',v_external_images,'measured_at',now());
end;
$$;
revoke all on function public.admin_resource_usage() from public;
grant execute on function public.admin_resource_usage() to authenticated;

