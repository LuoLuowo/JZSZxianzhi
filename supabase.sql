create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, nickname)
  values (new.id, coalesce(nullif(new.raw_user_meta_data ->> 'nickname',''), split_part(coalesce(new.email,'管理员'),'@',1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

